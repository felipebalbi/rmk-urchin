#!/usr/bin/env python3
"""Render the configured 34-key Urchin map and tertiary chords (Python 3.11+)."""
import hashlib
import html
from pathlib import Path
import re
import tomllib

ROOT = Path(__file__).resolve().parent.parent
SOURCE = (ROOT / "keyboard.toml").read_text(encoding="utf-8")
CONFIG = tomllib.loads(SOURCE)
LAYERS = CONFIG["keymap"]["layer"]
POSITIONS = [tuple(map(int, p)) for p in re.findall(r"\((\d+),(\d+),[LR]\)", CONFIG["layout"]["map"])]
COLORS = ["#f8f0d0", "#e0f6ff", "#e0f5e0", "#ffe8f0", "#eee0ff", "#fce0d0", "#e0f0f0"]
HOLDS = ["Typing / home-row modifiers", "Hold left Enter", "Hold left Tab",
         "Hold both left thumbs", "Hold right Space", "Hold right Backspace", "Hold both right thumbs"]
CHORDS = [("Escape / hold Media", "Delete / hold Fun"), ("Disabled", "Delete"),
          ("Disabled", "Middle click"), ("Disabled", "Mute"), ("Dot", "Disabled"),
          ("(", "Disabled"), ("Menu", "Disabled")]
NAMES = {"LShift": "L Shift", "RShift": "R Shift", "LAlt": "L Alt", "RAlt": "R Alt",
         "LGui": "L GUI", "RGui": "R GUI", "LCtrl": "L Ctrl", "RCtrl": "R Ctrl",
         "Semicolon": ";", "Comma": ",", "Dot": ".", "Slash": "/", "Quote": "'",
         "Grave": "`", "Minus": "-", "Equal": "=", "Backslash": "\\",
         "LeftBracket": "[", "RightBracket": "]", "Escape": "Esc", "Backspace": "Bksp",
         "PageDown": "PgDn", "PageUp": "PgUp", "PrintScreen": "PrtSc", "ScrollLock": "ScrLk",
         "Application": "Menu", "CapsWordToggle": "Caps Word", "MouseBtn1": "L click",
         "MouseBtn2": "R click", "MouseBtn3": "M click", "MediaPlayPause": "Play/Pause",
         "MediaStop": "Stop", "AudioMute": "Mute", "MediaPrevTrack": "Prev track",
         "MediaNextTrack": "Next track", "AudioVolDown": "Vol -", "AudioVolUp": "Vol +",
         "User0": "BT0", "User1": "BT1", "User2": "BT2", "User3": "BT3", "User7": "USB/BLE",
         "No": "—", "_": "▽", "TD(0)": "Boot ×2"}
SHIFTED = dict(zip("1234567890", "!@#$%^&*()")) | {
    "LeftBracket": "{", "RightBracket": "}", "Quote": '"', "Equal": "+",
    "Grave": "~", "Backslash": "|", "Minus": "_", "Insert": "Paste", "Delete": "Cut"}


def legends(action):
    if action.startswith("LT("):
        layer, tap, *_ = [a.strip() for a in action[3:-1].split(",")]
        return NAMES.get(tap, tap), "hold " + LAYERS[int(layer)]["name"]
    if action.startswith("MT("):
        tap, mod = [a.strip() for a in action[3:-1].split(",")]
        return NAMES.get(tap, tap), NAMES[mod]
    if action.startswith("WM("):
        key, mod = [a.strip() for a in action[3:-1].split(",")]
        if key == "Y" and mod == "LCtrl":
            return "Redo", "Ctrl+Y"
        if mod == "LShift":
            return SHIFTED[key], ""
        if key == "Insert" and mod == "LCtrl":
            return "Copy", ""
        return key, NAMES[mod]
    if action.startswith("MouseWheel"):
        return "Wheel", action.removeprefix("MouseWheel")
    if action.startswith("Mouse"):
        return NAMES.get(action, action.removeprefix("Mouse")), "" if "Btn" in action else "Pointer"
    return NAMES.get(action, action), ""


def generate():
    height = 150 + 520 * len(LAYERS)
    out = [f'<svg xmlns="http://www.w3.org/2000/svg" width="1200" height="{height}" viewBox="0 0 1200 {height}" role="img" aria-labelledby="title description">',
           '<title id="title">Urchin — QWERTY Miryoku, all seven layers</title>',
           '<desc id="description">34 physical keys. Same-hand two-thumb chords replace tertiary thumbs. Base: left chord Escape/Media, right chord Delete/Fun. Layer-specific chords are listed on every panel. Release both members to release a chord.</desc>',
           f'<metadata>keyboard.toml normalized-LF sha256: {hashlib.sha256(SOURCE.encode()).hexdigest()}; Modus Operandi palette; schematic placement; generated by assets/generate-keymap.py.</metadata>',
           '<style>text{font-family:"DejaVu Sans",sans-serif;fill:#000;text-anchor:middle}.title{font-size:28px;font-weight:700}.heading{font-size:21px;font-weight:700}.caption{font-size:14px;fill:#595959}.main{font-weight:600}.sub{font-size:12px;fill:#595959}.key{fill:#f2f2f2;stroke:#595959;stroke-width:1.3}.disabled{fill:#e0e0e0;stroke:#9f9f9f}</style>',
           '<rect width="1200" height="100%" fill="#fff"/>',
           '<text class="title" x="600" y="40">Urchin · QWERTY Miryoku</text>',
           '<text class="caption" x="600" y="69">34 keys · two thumbs per hand · US symbols · large legend: tap · lower legend: hold</text>',
           '<text class="caption" x="600" y="96">Thumb chord: press within 50 ms · hold 200 ms for layer · release BOTH keys to release output</text>']
    for index, layer in enumerate(LAYERS):
        top = 120 + index * 520
        out += [f'<g id="layer-{index}" data-layer="{layer["name"]}">',
                f'<rect x="50" y="{top}" width="1100" height="500" rx="16" fill="#fff" stroke="#9f9f9f"/>',
                f'<rect x="430" y="{top+12}" width="340" height="35" rx="8" fill="{COLORS[index]}"/>',
                f'<text class="heading" x="600" y="{top+37}">{index} · {layer["name"]}</text>',
                f'<text class="caption" x="600" y="{top+70}">{HOLDS[index]}</text>']
        actions = re.findall(r"[A-Za-z0-9_]+\([^)]*\)|\S+", layer["keys"])
        assert len(actions) == len(POSITIONS) == 34
        for (row, col), action in zip(POSITIONS, actions):
            if row == 3:
                x = {3: 385, 4: 465, 5: 735, 6: 815}[col]
                y = top + 385
            else:
                x = 145 + col * 80 + (190 if col >= 5 else 0)
                y = top + 145 + row * 72 + [35, 10, 0, 10, 25, 25, 10, 0, 10, 35][col]
            main, sub = legends(action)
            klass = "disabled" if action == "No" else "key"
            out += [f'<g class="binding" data-row="{row}" data-col="{col}" data-action="{html.escape(action, quote=True)}" transform="translate({x} {y})">',
                    f'<title>{layer["name"]} ({row},{col}): {html.escape(action)}</title>',
                    f'<rect class="{klass}" x="-36" y="-30" width="72" height="60" rx="8"/>',
                    f'<text class="main" x="0" y="{0 if sub else 6}" style="font-size:{min(21, 128/max(1,len(main))):.1f}px">{html.escape(main)}</text>']
            if sub:
                out.append(f'<text class="sub" x="0" y="20">{html.escape(sub)}</text>')
            out.append('</g>')
        for x, hand, chord in zip([330, 870], ["Left", "Right"], CHORDS[index]):
            out += [f'<rect x="{x-230}" y="{top+430}" width="460" height="52" rx="8" fill="{COLORS[index]}"/>',
                    f'<text class="caption" x="{x}" y="{top+451}">{hand} two-thumb chord</text>',
                    f'<text class="main" x="{x}" y="{top+472}">{html.escape(chord)}</text>']
        out.append('</g>')
    out.append('</svg>')
    (ROOT / "assets/keymap.svg").write_text("\n".join(out) + "\n", encoding="utf-8", newline="\n")


if __name__ == "__main__":
    generate()
